export const imageLookup = Object.fromEntries(
  allProjectImages.map((img) => [img.filename, img])
);

export function getImageMeta(filenameOrSrc, fallbackAlt = "The Hatha Yogashala Goa") {
  if (!filenameOrSrc) return { src: "", alt: fallbackAlt };
  const filename = filenameOrSrc.split("/").pop();
  if (imageLookup[filename]) {
    return imageLookup[filename];
  }
  return {
    src: filenameOrSrc,
    alt: fallbackAlt,
  };
}

